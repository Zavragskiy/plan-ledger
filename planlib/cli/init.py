"""`plan-init`: scaffold the plan state and the layout config.

Examples:
  plan-init                          # state in .planlib, tasks in backlog/tasks
  plan-init --state .                # root layout (the old behaviour)
  plan-init --config pyproject       # write [tool.plan-ledger] into pyproject.toml
  plan-init --with-placeholder       # + a bootstrap task so the first commit passes
  plan-init --tasks-base state       # legacy layouts: tasks inside state
  plan-init --dry-run                # show what would be created
"""

from __future__ import annotations

import argparse
import pathlib

from planlib import model
from planlib.console import enable_utf8

PLACEHOLDER_TITLE = "bootstrap: replace this placeholder with real tasks"
PLACEHOLDER_DESCRIPTION = (
    "Created by `plan-init --with-placeholder` so an empty plan does not block "
    "the first commit (plan-check with no tasks is exit 3).\n\n"
    "Next: create real tasks (`plan-task new ...`), then delete this file or "
    "mark the task Done after its acceptance run."
)

DODO_TEMPLATE = '''"""Plan shard acceptance.

Generated by `plan-init`. doit changes cwd to this file's directory, so:
* file_dep are built from ROOT (absolute paths at run time);
* every command pins cwd=ROOT, otherwise pytest/git inherit the dodo directory.
The DB lives next to the state: {db_path!r}.

Run acceptance through `plan-run <shard>`: it passes the same -f/-d/--db-file
as `plan-check`. A bare `doit` without `--db-file` puts the DB in the code root.
"""

from __future__ import annotations

import pathlib
import sys

from doit.action import CmdAction

ROOT = pathlib.Path(__file__).resolve().parent
STATE = ROOT / {state_rel!r}

DOIT_CONFIG = {{"verbosity": 2, "dep_file": str(STATE / {db_name!r})}}


def task_s1():
    """acceptance s1: replace the command and file_dep with real ones"""
    return {{
        "actions": [
            CmdAction(
                [sys.executable, "-c", "print('acceptance placeholder for s1')"],
                cwd=str(ROOT),
            )
        ],
        "file_dep": [str(ROOT / "dodo.py")],
        "verbosity": 2,
    }}
'''


def _write_config(
    root: pathlib.Path, table: dict[str, str], mode: str, force: bool, dry_run: bool
) -> pathlib.Path:
    lines = ["[plan-ledger]"] + [f'{key} = "{value}"' for key, value in table.items()] + [""]
    block = "\n".join(lines)
    if mode == "pyproject":
        target = root / "pyproject.toml"
        existing = target.read_text(encoding="utf-8") if target.is_file() else ""
        if "[tool.plan-ledger]" in existing:
            if not force:
                print(f"  = {target.name}: [tool.plan-ledger] already present, leaving it")
                return target
            print(
                "  ! pyproject already contains [tool.plan-ledger]; "
                "edit it manually when using --force"
            )
            return target
        marker = "" if not existing else ("\n" if existing.endswith("\n") else "\n\n")
        text = existing + marker + "[tool.plan-ledger]\n" + "\n".join(
            f'{key} = "{value}"' for key, value in table.items()
        ) + "\n"
        if not dry_run:
            target.write_text(text, encoding="utf-8")
        print(f"  + {target.name}: added the [tool.plan-ledger] table")
        return target
    target = root / "plan-ledger.toml"
    if target.is_file() and target.read_text(encoding="utf-8") == block and not force:
        print(f"  = {target.name}: already up to date")
        return target
    if target.is_file() and not force:
        print(f"  ! {target.name} already exists and differs; re-run with --force")
        return target
    if not dry_run:
        target.write_text(block, encoding="utf-8")
    print(f"  + {target.name}")
    return target


def _write_dodo(
    root: pathlib.Path, dodo_rel: str, state_rel: str, db_name: str, force: bool, dry_run: bool
) -> pathlib.Path:
    target = root / dodo_rel
    if target.is_file() and not force:
        print(f"  = {dodo_rel}: already exists (overwrite only with --force)")
        return target
    content = DODO_TEMPLATE.format(state_rel=state_rel, db_name=db_name, db_path=f"{state_rel}/{db_name}")
    if not dry_run:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    print(f"  + {dodo_rel}")
    return target


def _update_gitignore(root: pathlib.Path, entries: list[str], dry_run: bool) -> None:
    target = root / ".gitignore"
    existing = target.read_text(encoding="utf-8") if target.is_file() else ""
    lines = existing.splitlines()
    missing = [entry for entry in entries if not _ignored(entry, lines)]
    if not missing:
        print("  = .gitignore: already contains the required lines")
        return
    text = existing.rstrip("\n")
    text = (text + "\n" if text else "") + "\n".join(missing) + "\n"
    if not dry_run:
        target.write_text(text, encoding="utf-8")
    print("  + .gitignore: " + ", ".join(missing))


def _ignored(entry: str, lines: list[str]) -> bool:
    """True when an existing line already covers ``entry``.

    The exact `<db>*` entry stays exact, but the cache entry is covered by any
    of the common spellings the project may already have.
    """
    stripped = {line.strip() for line in lines}
    if entry in stripped:
        return True
    if entry != "__pycache__/":
        return False
    return bool(stripped & {"**/__pycache__", "__pycache__", "__pycache__/"})


def _placeholder(root: pathlib.Path, tasks_dir: pathlib.Path, dry_run: bool) -> None:
    """Bootstrap task: an empty plan is exit 3 and blocks the first commit."""
    existing = model.load_tasks(tasks_dir)
    if existing:
        print(f"  = the plan already has tasks ({len(existing)}): not creating a placeholder")
        return
    if dry_run:
        print(f"  + TASK-1 {PLACEHOLDER_TITLE} (placeholder)")
        return
    task = model.create(
        tasks_dir,
        title=PLACEHOLDER_TITLE,
        description=PLACEHOLDER_DESCRIPTION,
        labels=["bootstrap"],
        slug="bootstrap-placeholder",
    )
    try:
        shown = task.path.relative_to(root).as_posix()
    except ValueError:
        shown = str(task.path)
    print(f"  + {shown} (placeholder)")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="plan-init", description=__doc__)
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path("."), help="code root")
    parser.add_argument(
        "--state", type=pathlib.Path, default=pathlib.Path(".planlib"), help="state directory"
    )
    parser.add_argument(
        "--tasks",
        default="backlog/tasks",
        help="tasks directory: relative to the project root (default) or absolute",
    )
    parser.add_argument(
        "--tasks-base",
        choices=["config", "root", "state"],
        default="config",
        help="what --tasks is relative to: project root (config/root) or state",
    )
    parser.add_argument("--dodo", default="dodo.py", help="dodo file inside the code root")
    parser.add_argument("--db", default=".doit.db", help="doit DB file inside the state")
    parser.add_argument(
        "--config", choices=["toml", "pyproject"], default="toml", help="where to write the config"
    )
    parser.add_argument("--force", action="store_true", help="overwrite dodo.py and the config")
    parser.add_argument("--dry-run", action="store_true", help="write nothing")
    parser.add_argument(
        "--with-placeholder",
        action="store_true",
        help="create a bootstrap task so an empty plan does not block the first commit",
    )
    enable_utf8()
    args = parser.parse_args(argv)

    root = (pathlib.Path.cwd() / args.root).resolve()
    state = (pathlib.Path.cwd() / args.state).resolve()
    if not root.is_dir():
        print(f"no project directory: {root}")
        return 3
    try:
        state_rel = state.relative_to(root).as_posix() or "."
    except ValueError:
        print(f"state {state} must be inside {root}")
        return 3
    if args.db.startswith("/") or ".." in pathlib.PurePosixPath(args.db).parts:
        print("--db must be a path inside the state directory")
        return 3

    tasks_path = pathlib.Path(args.tasks)
    base_dir = state if args.tasks_base == "state" else root
    tasks_dir = tasks_path if tasks_path.is_absolute() else base_dir / tasks_path
    tasks_dir = tasks_dir.resolve()
    try:
        shown_tasks = tasks_dir.relative_to(root).as_posix()
    except ValueError:
        shown_tasks = str(tasks_dir)
    print(f"Layout: root={root}, state={state_rel}, tasks={shown_tasks}")
    if not args.dry_run:
        # state нужен всегда: в нём лежит БД doit, даже если задачи вынесены в корень.
        if state != root:
            if not state.exists():
                state.mkdir(parents=True, exist_ok=True)
                print(f"  + {state_rel}/")
            # Пустой каталог не переживает clone; .gitkeep делает state отслеживаемым.
            state_keep = state / ".gitkeep"
            if not state_keep.exists():
                state_keep.write_text("", encoding="utf-8")
        tasks_dir.mkdir(parents=True, exist_ok=True)
        keep = tasks_dir / ".gitkeep"
        if not keep.exists():
            keep.write_text("", encoding="utf-8")
        print(f"  + {shown_tasks}/")

    if args.with_placeholder:
        _placeholder(root, tasks_dir, args.dry_run)

    table = {
        "root": ".",
        "state": state_rel,
        "tasks": args.tasks,
        "tasks_base": args.tasks_base,
        "dodo": args.dodo,
        "db": args.db,
    }
    _write_config(root, table, args.config, args.force, args.dry_run)
    _write_dodo(root, args.dodo, state_rel, args.db, args.force, args.dry_run)
    db_entry = f"{state_rel}/{args.db}" if state_rel != "." else args.db
    _update_gitignore(root, [f"{db_entry}*", "__pycache__/"], args.dry_run)

    if args.dry_run:
        print("\ndry-run: nothing was created")
        return 0
    print(
        "\nDone. Next:\n"
        "  plan-task new \"s1: first shard\" --ac \"<acceptance command>\" --shard s1\n"
        "  plan-run s1\n"
        "  plan-task set task-1 --status Done --check-ac 1 --note \"plan-run s1 — passed\"\n"
        "  plan-check"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
